"""CodeQL Ada extractor: Libadalang AST -> TRAP files.

Invoked by `codeql database create --language=ada --build-mode=none` via
tools/autobuild.sh, with cwd = source root and CODEQL_EXTRACTOR_ADA_* env vars.
Table layout comes from ada_tables.json, generated by generator/gen.py from the
same Libadalang introspection dump as the dbscheme (decision D-004).

Project discovery (decision D-003): explicit CODEQL_EXTRACTOR_ADA_GPR env var ->
single .gpr found under the source root -> auto unit provider over all Ada files.

Node identity: nodes are keyed by (file, kind, source span). This is stable and
computable from any reference to the node (needed for cross-unit xref), at the
cost of merging pathological same-kind-same-span nodes. Cross-unit references
are only emitted when the target lies in an extracted file.
"""

import json
import os
import pathlib
import shutil
import sys
import time

import libadalang as lal

LANG = "ADA"
EXTENSIONS = {".ads", ".adb", ".ada"}
TABLES = json.loads(
    (pathlib.Path(__file__).parent / "ada_tables.json").read_text("utf-8")
)

DIAG_ERROR = 40
DIAG_WARNING = 30


def env_path(suffix: str) -> pathlib.Path:
    return pathlib.Path(os.environ[f"CODEQL_EXTRACTOR_{LANG}_{suffix}"])


def norm(path) -> str:
    return str(pathlib.Path(path).resolve()).replace("\\", "/")


def q(s: str) -> str:
    """TRAP string literal."""
    return '"' + s.replace('"', '""') + '"'


class TrapWriter:
    """One TRAP file; labels are file-local, global identity via @"key"."""

    def __init__(self):
        self.lines = []
        self.labels = {}
        self.next_id = 10000

    def label(self, key: str) -> str:
        lbl = self.labels.get(key)
        if lbl is None:
            lbl = f"#{self.next_id}"
            self.next_id += 1
            self.labels[key] = lbl
            self.lines.append(f'{lbl}=@{q(key)}')
        return lbl

    def fresh(self) -> str:
        lbl = f"#{self.next_id}"
        self.next_id += 1
        self.lines.append(f"{lbl}=*")
        return lbl

    def row(self, table: str, *args):
        self.lines.append(f"{table}({','.join(args)})")

    def text(self) -> str:
        return "\n".join(self.lines) + "\n"


def node_key(node: lal.AdaNode) -> str:
    s = node.sloc_range
    return (f"{norm(node.unit.filename)};{node.kind_name};"
            f"{s.start.line}:{s.start.column}-{s.end.line}:{s.end.column}")


def file_key(path: str) -> str:
    return f"{path};sourcefile"


class Extractor:
    def __init__(self, sources):
        self.sources = {norm(s) for s in sources}
        self.stats = {"nodes": 0, "xref": 0, "types": 0, "diags": 0,
                      "nameres_errors": 0}

    def emit_file_tree(self, w: TrapWriter, path: str) -> str:
        """files() row plus folder chain; returns the file label."""
        f = w.label(file_key(path))
        w.row("files", f, q(path))
        child, child_path = f, path
        while True:
            parent_path = str(pathlib.PurePosixPath(child_path).parent)
            if parent_path == child_path:
                break
            p = w.label(f"{parent_path};folder")
            w.row("folders", p, q(parent_path))
            w.row("containerparent", p, child)
            child, child_path = p, parent_path
        return f

    def location(self, w: TrapWriter, file_lbl: str, path: str, node) -> str:
        s = node.sloc_range
        key = (f"loc,{path},{s.start.line},{s.start.column},"
               f"{s.end.line},{s.end.column}")
        known = key in w.labels
        lbl = w.label(key)
        if not known:
            w.row("locations_default", lbl, file_lbl,
                  str(s.start.line), str(s.start.column),
                  str(s.end.line), str(s.end.column))
        return lbl

    def diagnostic(self, w, severity, tag, msg, loc_lbl):
        d = w.fresh()
        w.row("diagnostics", d, str(severity), q(tag), q(msg), q(msg), loc_lbl)
        self.stats["diags"] += 1

    def extract_unit(self, unit: lal.AnalysisUnit, trap_dir: pathlib.Path):
        path = norm(unit.filename)
        w = TrapWriter()
        file_lbl = self.emit_file_tree(w, path)

        for d in unit.diagnostics:
            key = (f"loc,{path},{d.sloc_range.start.line},"
                   f"{d.sloc_range.start.column},{d.sloc_range.end.line},"
                   f"{d.sloc_range.end.column}")
            known = key in w.labels
            loc = w.label(key)
            if not known:
                w.row("locations_default", loc, file_lbl,
                      str(d.sloc_range.start.line), str(d.sloc_range.start.column),
                      str(d.sloc_range.end.line), str(d.sloc_range.end.column))
            self.diagnostic(w, DIAG_ERROR, "parse-error", str(d.message), loc)

        if unit.root is not None:
            self.walk(w, file_lbl, path, unit.root, None, 0)

        name = path.replace(":", "_").replace("/", "_") + ".trap"
        (trap_dir / name).write_text(w.text(), encoding="utf-8")

    def walk(self, w, file_lbl, path, node, parent_lbl, index):
        kind = node.kind_name
        spec = TABLES.get(kind)
        if spec is None:
            return  # kind unknown to the schema; skip subtree
        lbl = w.label(node_key(node))
        self.stats["nodes"] += 1

        if spec["is_token"]:
            w.row(spec["def_table"], lbl, q(node.text))
        else:
            w.row(spec["def_table"], lbl)

        w.row("ada_ast_node_location", lbl,
              self.location(w, file_lbl, path, node))
        if parent_lbl is not None:
            w.row("ada_ast_node_parent", lbl, parent_lbl, str(index))

        for f in spec["fields"]:
            child = getattr(node, f["name"], None)
            if child is not None:
                w.row(f["table"], lbl, w.label(node_key(child)))

        self.semantics(w, node, lbl)

        for i, child in enumerate(node.children):
            if child is not None:
                self.walk(w, file_lbl, path, child, lbl, i)

    def in_sources(self, node) -> bool:
        return node is not None and norm(node.unit.filename) in self.sources

    def semantics(self, w, node, lbl):
        try:
            if isinstance(node, lal.Name) and not node.p_is_defining:
                decl = node.p_referenced_decl()
                if self.in_sources(decl):
                    w.row("ada_xref", lbl, w.label(node_key(decl)))
                    self.stats["xref"] += 1
            if isinstance(node, lal.Expr):
                t = node.p_expression_type
                if self.in_sources(t):
                    w.row("ada_expr_type", lbl, w.label(node_key(t)))
                    self.stats["types"] += 1
            if isinstance(node, lal.GenericInstantiation):
                d = node.p_designated_generic_decl
                if self.in_sources(d):
                    w.row("ada_generic_instantiation", lbl,
                          w.label(node_key(d)))
        except lal.PropertyError:
            self.stats["nameres_errors"] += 1
        except Exception:
            self.stats["nameres_errors"] += 1


def find_gpr(src_root: pathlib.Path):
    gpr = os.environ.get("CODEQL_EXTRACTOR_ADA_GPR")
    if not gpr:
        gprs = sorted(src_root.rglob("*.gpr"))
        if len(gprs) == 1:
            gpr = str(gprs[0])
    return gpr


def project_files(src_root: pathlib.Path, gpr):
    if gpr:
        return [f for f in lal.GPRProject(gpr).source_files()
                if pathlib.Path(f).suffix.lower() in EXTENSIONS]
    return sorted(
        str(p) for p in src_root.rglob("*")
        if p.suffix.lower() in EXTENSIONS and p.is_file()
    )


def build_context(gpr, ada_files) -> lal.AnalysisContext:
    if gpr:
        return lal.GPRProject(gpr).create_context()
    provider = lal.UnitProvider.auto(input_files=ada_files)
    return lal.AnalysisContext(unit_provider=provider)


# Per-worker state (LAL contexts are neither picklable nor thread-safe, so
# parallelism is one context per forked process).
_state = None


def _init_worker(gpr, files, trap_dir, archive_dir):
    global _state
    _state = (build_context(gpr, files), Extractor(files), trap_dir, archive_dir)


def _extract_one(f):
    ctx, ex, trap_dir, archive_dir = _state
    ex.stats = dict.fromkeys(ex.stats, 0)
    path = norm(f)
    unit = ctx.get_from_file(f)
    ex.extract_unit(unit, trap_dir)
    dest = archive_dir / path.replace(":", "_").lstrip("/")
    dest.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(f, dest)
    return path, ex.stats


def main() -> int:
    t0 = time.monotonic()
    trap_dir = env_path("TRAP_DIR")
    archive_dir = env_path("SOURCE_ARCHIVE_DIR")
    src_root = pathlib.Path.cwd()
    trap_dir.mkdir(parents=True, exist_ok=True)
    archive_dir.mkdir(parents=True, exist_ok=True)

    gpr = find_gpr(src_root)
    print(f"[ada-extractor] project: {gpr or 'none (auto unit provider)'}")
    files = project_files(src_root, gpr)

    (trap_dir / "metadata.trap").write_text(
        f"sourceLocationPrefix({q(norm(src_root))})\n", encoding="utf-8"
    )

    jobs = int(os.environ.get("CODEQL_EXTRACTOR_ADA_JOBS",
                              str(os.cpu_count() or 1)))
    jobs = max(1, min(jobs, len(files) or 1))
    totals = dict.fromkeys(
        ("nodes", "xref", "types", "diags", "nameres_errors"), 0)

    if jobs == 1 or not hasattr(os, "fork"):
        _init_worker(gpr, files, trap_dir, archive_dir)
        results = map(_extract_one, files)
        self_stats = [r for r in results]
    else:
        import multiprocessing
        with multiprocessing.Pool(
            jobs, _init_worker, (gpr, files, trap_dir, archive_dir)
        ) as pool:
            self_stats = pool.map(_extract_one, files, chunksize=4)

    for path, st in self_stats:
        print(f"[ada-extractor] {path}")
        for k, v in st.items():
            totals[k] += v

    dt = time.monotonic() - t0
    print(f"[ada-extractor] {len(files)} files in {dt:.1f}s "
          f"({jobs} jobs): {totals}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
