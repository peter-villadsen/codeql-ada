"""Phase 2 generator: schema/lal-nodes.json -> dbscheme + QL classes + extractor tables.

Outputs (all generated-but-committed, per docs/dbscheme-conventions.md):
  extractors/ada/ada.dbscheme
  ql/lib/ada.dbscheme                        (copy)
  ql/lib/codeql/ada/ast/internal/Raw.qll
  extractors/ada/tools/ada_tables.json       (kind -> table map for the extractor)

Conventions:
  - Every concrete kind K gets an entity tag @ada_<snake(K)> and a table
    ada_<snake(K)>_def(unique int id) (token kinds add a `string value` column).
  - Every class with subclasses gets a union covering all its concrete
    descendants; concrete non-leaf classes include their own tag in the union
    (named @ada_<snake>_or_sub to avoid colliding with their tag).
  - A field declared on class C gets one table ada_<snake(C)>_<field>(
    unique int parent: ref(C), int value: ref(field type)); required-ness is
    an extractor guarantee, not a schema constraint (parse errors can null
    "never null" fields).
  - Tree structure and list children live in ada_ast_node_parent(node, parent,
    parent_index); no per-kind child tables.
"""

import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SCHEMA = ROOT / "schema" / "lal-nodes.json"

RESERVED_ACCESSORS = {
    "getParent", "getParentIndex", "getLocation", "getFile", "getChild",
    "toString", "getAPrimaryQlClass", "getValue",
}

PRELUDE = """\
/*- Standard fragment: locations, files, folders -*/

locations_default(
  unique int id: @location_default,
  int file: @file ref,
  int beginLine: int ref,
  int beginColumn: int ref,
  int endLine: int ref,
  int endColumn: int ref
);

files(
  unique int id: @file,
  string name: string ref
);

folders(
  unique int id: @folder,
  string name: string ref
);

@container = @file | @folder

containerparent(
  int parent: @container ref,
  unique int child: @container ref
);

/*- Standard fragment: empty location -*/

empty_location(
  int location: @location_default ref
);

/*- Standard fragment: source location prefix -*/

sourceLocationPrefix(string prefix : string ref);

/*- Standard fragment: diagnostics -*/

diagnostics(
  unique int id: @diagnostic,
  int severity: int ref,
  string error_tag: string ref,
  string error_message: string ref,
  string full_error_message: string ref,
  int location: @location_default ref
);

case @diagnostic.severity of
  10 = @diagnostic_debug
| 20 = @diagnostic_info
| 30 = @diagnostic_warning
| 40 = @diagnostic_error
;

/*- Standard fragment: database metadata / overlay support -*/

databaseMetadata(
  string metadataKey: string ref,
  string value: string ref
);

overlayChangedFiles(
  string path: string ref
);
"""


def snake(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def accessor(field: str) -> str:
    return "get" + "".join(w.capitalize() for w in field[2:].split("_"))


class Model:
    def __init__(self, data):
        self.nodes = {n["name"]: n for n in data["nodes"]}
        self.children = {name: [] for name in self.nodes}
        for n in data["nodes"]:
            if n["name"] != "AdaNode":
                self.children[n["base"]].append(n["name"])
        for c in self.children.values():
            c.sort()

    def tag(self, name: str) -> str:
        return f"@ada_{snake(name)}"

    def concrete_descendants(self, name: str) -> list:
        out = []
        if self.nodes[name]["concrete"]:
            out.append(name)
        for c in self.children[name]:
            out.extend(self.concrete_descendants(c))
        return out

    def ref(self, name: str) -> str:
        """Type reference covering `name` and all its concrete descendants."""
        if name == "AdaNode":
            return "@ada_ast_node"
        if not self.children[name]:
            assert self.nodes[name]["concrete"], f"childless abstract {name}"
            return self.tag(name)
        if self.nodes[name]["concrete"]:
            return self.tag(name) + "_or_sub"
        return self.tag(name)

    def field_table(self, cls: str, field: str) -> str:
        return f"ada_{snake(cls)}_{field[2:]}"

    def declaring_class(self, cls: str, field: str) -> str:
        c = cls
        while c:
            if any(f["name"] == field for f in self.nodes[c]["fields"]):
                return c
            c = self.nodes[c].get("base") if c != "AdaNode" else None
        raise KeyError(f"{field} not declared on {cls} or ancestors")


def gen_dbscheme(m: Model) -> str:
    out = [
        "// CodeQL database schema for Ada",
        "// Generated by generator/gen.py from schema/lal-nodes.json; do not edit.",
        "",
        PRELUDE,
        "/*- Ada AST: entity types and hierarchy unions -*/",
        "",
    ]
    all_concrete = sorted(
        n["name"] for n in m.nodes.values() if n["concrete"]
    )
    out.append(
        "@ada_ast_node =\n    "
        + "\n  | ".join(m.tag(n) for n in all_concrete)
        + "\n"
    )
    for name in sorted(m.nodes):
        if name == "AdaNode" or not m.children[name]:
            continue
        node = m.nodes[name]
        parts = []
        if node["concrete"]:
            parts.append(m.tag(name))
        parts.extend(m.ref(c) for c in m.children[name])
        out.append(f"{m.ref(name)} =\n    " + "\n  | ".join(parts) + "\n")

    out.append("/*- Ada AST: node kind tables -*/\n")
    for name in all_concrete:
        node = m.nodes[name]
        tbl = f"ada_{snake(name)}_def"
        if node["is_token_node"]:
            out.append(
                f"{tbl}(\n  unique int id: {m.tag(name)},\n"
                f"  string value: string ref\n);\n"
            )
        else:
            out.append(f"{tbl}(\n  unique int id: {m.tag(name)}\n);\n")

    out.append("/*- Ada AST: syntax fields -*/\n")
    for name in sorted(m.nodes):
        node = m.nodes[name]
        for f in node["fields"]:
            out.append(
                f"{m.field_table(name, f['name'])}(\n"
                f"  unique int parent: {m.ref(name)} ref,\n"
                f"  int value: {m.ref(f['type'])} ref\n);\n"
            )

    out.append("/*- Ada AST: tree structure and locations -*/\n")
    out.append(
        "ada_ast_node_location(\n"
        "  unique int node: @ada_ast_node ref,\n"
        "  int loc: @location_default ref\n);\n"
    )
    out.append(
        "#keyset[parent, parent_index]\n"
        "ada_ast_node_parent(\n"
        "  unique int node: @ada_ast_node ref,\n"
        "  int parent: @ada_ast_node ref,\n"
        "  int parent_index: int ref\n);\n"
    )

    out.append("/*- Ada semantics: name resolution and types -*/\n")
    out.append(
        "ada_xref(\n"
        f"  unique int ref_node: {m.ref('Name')} ref,\n"
        f"  int decl: {m.ref('BasicDecl')} ref\n);\n"
    )
    out.append(
        "ada_expr_type(\n"
        f"  unique int expr: {m.ref('Expr')} ref,\n"
        f"  int type_decl: {m.ref('BaseTypeDecl')} ref\n);\n"
    )
    out.append(
        "ada_generic_instantiation(\n"
        f"  unique int inst: {m.ref('GenericInstantiation')} ref,\n"
        f"  int generic_decl: {m.ref('BasicDecl')} ref\n);\n"
    )
    out.append(
        "ada_body_part(\n"
        f"  unique int decl: {m.ref('BasicDecl')} ref,\n"
        f"  int body: {m.ref('BasicDecl')} ref\n);\n"
    )
    out.append(
        "ada_qualified_name(\n"
        f"  unique int decl: {m.ref('BasicDecl')} ref,\n"
        "  string name: string ref\n);\n"
    )
    out.append("/*- Ada predefined pseudo-sources: Standard and runtime units (D-026) -*/\n")
    out.append(
        "ada_predefined_file(\n"
        "  unique int file: @file ref\n);\n"
    )
    out.append("/*- Ada trivia: comments (not part of the AST tree) -*/\n")
    out.append(
        "ada_comments(\n"
        "  unique int id: @ada_comment,\n"
        "  string text: string ref,\n"
        "  int location: @location_default ref\n);\n"
    )
    return "\n".join(out)


def gen_raw_qll(m: Model) -> str:
    out = [
        "/**",
        " * Generated QL classes mirroring the Libadalang AST.",
        " * Generated by generator/gen.py from schema/lal-nodes.json; do not edit.",
        " */",
        "",
        "module Raw {",
        "  /** A location in the snapshot. */",
        "  class Location extends @location_default {",
        "    predicate hasLocationInfo(",
        "      string filepath, int startline, int startcolumn, int endline, int endcolumn",
        "    ) {",
        "      exists(File f |",
        "        locations_default(this, f, startline, startcolumn, endline, endcolumn) and",
        "        filepath = f.getAbsolutePath()",
        "      )",
        "    }",
        "",
        "    /** Gets the 1-based line number (inclusive) where this location starts. */",
        "    int getStartLine() { this.hasLocationInfo(_, result, _, _, _) }",
        "",
        "    /** Gets the 1-based column number (inclusive) where this location starts. */",
        "    int getStartColumn() { this.hasLocationInfo(_, _, result, _, _) }",
        "",
        "    /** Gets the 1-based line number (inclusive) where this location ends. */",
        "    int getEndLine() { this.hasLocationInfo(_, _, _, result, _) }",
        "",
        "    /** Gets the 1-based column number (inclusive) where this location ends. */",
        "    int getEndColumn() { this.hasLocationInfo(_, _, _, _, result) }",
        "",
        "    string toString() {",
        "      exists(string path, int line |",
        "        this.hasLocationInfo(path, line, _, _, _) and",
        '        result = path + ":" + line.toString()',
        "      )",
        "    }",
        "  }",
        "",
        "  /** A file in the snapshot. */",
        "  class File extends @file {",
        "    string getAbsolutePath() { files(this, result) }",
        "",
        "    string toString() { result = this.getAbsolutePath() }",
        "  }",
        "",
        "  /** A source comment (`--...` trivia; not part of the AST tree). */",
        "  class Comment extends @ada_comment {",
        "    string getText() { ada_comments(this, result, _) }",
        "",
        "    Location getLocation() { ada_comments(this, _, result) }",
        "",
        "    string toString() { result = \"Comment\" }",
        "  }",
        "",
    ]

    def emit_class(name: str, indent: str = "  "):
        node = m.nodes[name]
        if name == "AdaNode":
            header = f"class AdaNode extends @ada_ast_node {{"
        else:
            header = f"class {name} extends {node['base']}, {m.ref(name)} {{"
        body = []
        if name == "AdaNode":
            body += [
                'string getAPrimaryQlClass() { result = "AdaNode" }',
                "string toString() { result = this.getAPrimaryQlClass() }",
                "Location getLocation() { ada_ast_node_location(this, result) }",
                "AdaNode getParent() { ada_ast_node_parent(this, result, _) }",
                "int getParentIndex() { ada_ast_node_parent(this, _, result) }",
                "AdaNode getChild(int i) { ada_ast_node_parent(result, this, i) }",
            ]
        if node["concrete"]:
            body.append(
                "override string getAPrimaryQlClass() "
                f'{{ result = "{name}" }}'
            )
            if node["is_token_node"]:
                body.append(
                    "string getValue() "
                    f"{{ ada_{snake(name)}_def(this, result) }}"
                )
        for f in node["fields"]:
            acc = accessor(f["name"])
            assert acc not in RESERVED_ACCESSORS, (name, acc)
            body.append(
                f"{f['type']} {acc}() "
                f"{{ {m.field_table(name, f['name'])}(this, result) }}"
            )
        if body:
            out.append(indent + header)
            for b in body:
                out.append(indent + "  " + b)
                out.append("")
            out.pop()
            out.append(indent + "}")
        else:
            out.append(indent + header + " }")
        out.append("")
        for c in m.children[name]:
            emit_class(c, indent)

    emit_class("AdaNode")
    out.append("}")
    return "\n".join(out)


def gen_tables_json(m: Model) -> dict:
    kinds = {}
    for name, node in sorted(m.nodes.items()):
        if not node["concrete"]:
            continue
        fields = []
        for f in node["all_field_order"]:
            decl = m.declaring_class(name, f)
            spec = next(
                x for x in m.nodes[decl]["fields"] if x["name"] == f
            )
            fields.append({
                "name": f,
                "table": m.field_table(decl, f),
                "nullable": spec["nullable"],
            })
        kinds[node["kind_name"]] = {
            "def_table": f"ada_{snake(name)}_def",
            "is_token": node["is_token_node"],
            "is_list": node["is_list_node"],
            "fields": fields,
        }
    return kinds


def main():
    m = Model(json.loads(SCHEMA.read_text(encoding="utf-8")))
    dbscheme = gen_dbscheme(m)
    (ROOT / "extractors/ada/ada.dbscheme").write_text(dbscheme, encoding="utf-8")
    (ROOT / "ql/lib/ada.dbscheme").write_text(dbscheme, encoding="utf-8")
    raw = gen_raw_qll(m)
    p = ROOT / "ql/lib/codeql/ada/ast/internal/Raw.qll"
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(raw, encoding="utf-8")
    tables = gen_tables_json(m)
    (ROOT / "extractors/ada/tools/ada_tables.json").write_text(
        json.dumps(tables, indent=1), encoding="utf-8"
    )
    n_tables = dbscheme.count("(\n  unique int") + dbscheme.count("(\n  int")
    print(f"dbscheme: {len(dbscheme.splitlines())} lines")
    print(f"Raw.qll: {len(raw.splitlines())} lines")
    print(f"tables.json: {len(tables)} kinds")


if __name__ == "__main__":
    main()
