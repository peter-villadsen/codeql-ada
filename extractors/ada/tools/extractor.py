"""CodeQL Ada extractor: Libadalang AST -> TRAP files.

Invoked by `codeql database create --language=ada --build-mode=none` via
tools/autobuild.sh, with cwd = source root and CODEQL_EXTRACTOR_ADA_* env vars.
Table layout comes from ada_tables.json, generated by generator/gen.py from the
same Libadalang introspection dump as the dbscheme (decision D-004).

Project discovery (decision D-003): explicit CODEQL_EXTRACTOR_ADA_GPR env var ->
single .gpr found under the source root -> auto unit provider over all Ada files.

Runtime discovery (burndown 8.12a): the auto unit provider only knows the files
it is given, and without the GNAT runtime specs Libadalang fails to resolve any
statement that mentions a runtime entity -- including the user's own names in
it. So the auto provider is also given the runtime's *.ads files, found via
CODEQL_EXTRACTOR_ADA_RUNTIME -> `gcc -print-file-name=adainclude`. A GPR
project finds its runtime by itself.

Predefined pseudo-sources (burndown 8.12b, decision D-026): extraction runs in
two passes. Pass 1 extracts the project files (in parallel) and emits semantic
rows for *any* resolved target, recording which out-of-project units those
targets land in -- package Standard and the runtime units the project refers to
directly. Pass 2 extracts exactly those units, marked in `ada_predefined_file`,
with semantic rows limited to targets in the project or the pass-2 set, so there
is no transitive closure. Standard has no file of its own (Libadalang names it
`<cwd>/__standard`), so it gets the fixed pseudo path STANDARD_PATH and its text
is written to the source archive directly.

Node identity: nodes are keyed by (file, kind, source span). This is stable and
computable from any reference to the node (needed for cross-unit xref), at the
cost of merging pathological same-kind-same-span nodes. Cross-unit references
are only emitted when the target lies in an extracted file; an out-of-project
target must also be reachable by walking its unit's tree, which excludes
Libadalang's synthetic nodes (predefined operators, class-wide types, ...).
"""

import functools
import json
import os
import pathlib
import re
import shutil
import subprocess
import sys
import time

import libadalang as lal

LANG = "ADA"
EXTENSIONS = {".ads", ".adb", ".ada"}
TABLES = json.loads(
    (pathlib.Path(__file__).parent / "ada_tables.json").read_text("utf-8")
)

DIAG_ERROR = 40
DIAG_WARNING = 30

# Package Standard's path in the database: fixed, and outside any source root.
STANDARD_PATH = "/__codeql_ada_predefined__/standard.ads"


def env_path(suffix: str) -> pathlib.Path:
    return pathlib.Path(os.environ[f"CODEQL_EXTRACTOR_{LANG}_{suffix}"])


def norm(path) -> str:
    return str(pathlib.Path(path).resolve()).replace("\\", "/")


def q(s: str) -> str:
    """TRAP string literal."""
    return '"' + s.replace('"', '""') + '"'


class TrapWriter:
    """One TRAP file; labels are file-local, global identity via @"key"."""

    def __init__(self):
        self.lines = []
        self.labels = {}
        self.next_id = 10000

    def label(self, key: str) -> str:
        lbl = self.labels.get(key)
        if lbl is None:
            lbl = f"#{self.next_id}"
            self.next_id += 1
            self.labels[key] = lbl
            self.lines.append(f'{lbl}=@{q(key)}')
        return lbl

    def fresh(self) -> str:
        lbl = f"#{self.next_id}"
        self.next_id += 1
        self.lines.append(f"{lbl}=*")
        return lbl

    def row(self, table: str, *args):
        self.lines.append(f"{table}({','.join(args)})")

    def text(self) -> str:
        return "\n".join(self.lines) + "\n"


@functools.lru_cache(maxsize=None)
def path_of(filename: str) -> str:
    """Database path of the unit Libadalang calls `filename`."""
    if os.path.basename(filename) == "__standard" and not os.path.exists(filename):
        return STANDARD_PATH
    return norm(filename)


def node_key(node: lal.AdaNode) -> str:
    s = node.sloc_range
    return (f"{path_of(node.unit.filename)};{node.kind_name};"
            f"{s.start.line}:{s.start.column}-{s.end.line}:{s.end.column}")


def file_key(path: str) -> str:
    return f"{path};sourcefile"


class Extractor:
    def __init__(self, sources, predefined=None):
        """`predefined`: None in pass 1 (accept any walkable out-of-project
        target, recording its unit in `out_units`), else the set of pass-2
        unit paths that out-of-project targets are limited to."""
        self.sources = {norm(s) for s in sources}
        self.predefined = predefined
        self.out_units = set()
        self._walkable = {}
        self.stats = {"nodes": 0, "xref": 0, "types": 0, "diags": 0,
                      "nameres_errors": 0, "comments": 0, "body_part": 0,
                      "body_part_syntactic": 0}

    def emit_file_tree(self, w: TrapWriter, path: str) -> str:
        """files() row plus folder chain; returns the file label."""
        f = w.label(file_key(path))
        w.row("files", f, q(path))
        child, child_path = f, path
        while True:
            parent_path = str(pathlib.PurePosixPath(child_path).parent)
            if parent_path == child_path:
                break
            p = w.label(f"{parent_path};folder")
            w.row("folders", p, q(parent_path))
            w.row("containerparent", p, child)
            child, child_path = p, parent_path
        return f

    def location(self, w: TrapWriter, file_lbl: str, path: str, node) -> str:
        s = node.sloc_range
        key = (f"loc,{path},{s.start.line},{s.start.column},"
               f"{s.end.line},{s.end.column}")
        known = key in w.labels
        lbl = w.label(key)
        if not known:
            w.row("locations_default", lbl, file_lbl,
                  str(s.start.line), str(s.start.column),
                  str(s.end.line), str(s.end.column))
        return lbl

    def diagnostic(self, w, severity, tag, msg, loc_lbl):
        d = w.fresh()
        w.row("diagnostics", d, str(severity), q(tag), q(msg), q(msg), loc_lbl)
        self.stats["diags"] += 1

    def extract_unit(self, unit: lal.AnalysisUnit, trap_dir: pathlib.Path,
                     predefined=False):
        path = path_of(unit.filename)
        w = TrapWriter()
        file_lbl = self.emit_file_tree(w, path)
        if predefined:
            w.row("ada_predefined_file", file_lbl)

        for d in unit.diagnostics:
            key = (f"loc,{path},{d.sloc_range.start.line},"
                   f"{d.sloc_range.start.column},{d.sloc_range.end.line},"
                   f"{d.sloc_range.end.column}")
            known = key in w.labels
            loc = w.label(key)
            if not known:
                w.row("locations_default", loc, file_lbl,
                      str(d.sloc_range.start.line), str(d.sloc_range.start.column),
                      str(d.sloc_range.end.line), str(d.sloc_range.end.column))
            self.diagnostic(w, DIAG_ERROR, "parse-error", str(d.message), loc)

        if unit.root is not None:
            self.walk(w, file_lbl, path, unit.root, None, 0)

        self.emit_comments(w, file_lbl, path, unit)

        name = path.replace(":", "_").replace("/", "_") + ".trap"
        (trap_dir / name).write_text(w.text(), encoding="utf-8")

    def emit_comments(self, w, file_lbl, path, unit: lal.AnalysisUnit):
        """Comment trivia isn't part of the AST tree; walk tokens directly."""
        tok = unit.first_token
        while tok is not None:
            if tok.is_trivia and tok.kind == "Comment":
                loc = self.location(w, file_lbl, path, tok)
                c = w.fresh()
                w.row("ada_comments", c, q(tok.text), loc)
                self.stats["comments"] += 1
            tok = tok.next

    def walk(self, w, file_lbl, path, node, parent_lbl, index):
        kind = node.kind_name
        spec = TABLES.get(kind)
        if spec is None:
            return  # kind unknown to the schema; skip subtree
        lbl = w.label(node_key(node))
        self.stats["nodes"] += 1

        if spec["is_token"]:
            w.row(spec["def_table"], lbl, q(node.text))
        else:
            w.row(spec["def_table"], lbl)

        w.row("ada_ast_node_location", lbl,
              self.location(w, file_lbl, path, node))
        if parent_lbl is not None:
            w.row("ada_ast_node_parent", lbl, parent_lbl, str(index))

        for f in spec["fields"]:
            child = getattr(node, f["name"], None)
            if child is not None:
                w.row(f["table"], lbl, w.label(node_key(child)))

        self.semantics(w, node, lbl)

        for i, child in enumerate(node.children):
            if child is not None:
                self.walk(w, file_lbl, path, child, lbl, i)

    def is_walkable(self, t) -> bool:
        """Holds if `walk` reaches `t` from its unit's root, so a row pointing
        at it cannot dangle. Libadalang's synthetic nodes are not among their
        parent's children. Instantiated-generic targets are distinct objects
        from the generic's own nodes, hence the comparison by key."""
        key = node_key(t)
        ok = self._walkable.get(key)
        if ok is None:
            p = t.parent
            ok = TABLES.get(t.kind_name) is not None and (
                p is None or any(c is not None and node_key(c) == key
                                 for c in p.children))
            self._walkable[key] = ok
        return ok

    def accept(self, t) -> bool:
        """Holds if a semantic row may point at `t`."""
        if t is None:
            return False
        path = path_of(t.unit.filename)
        if path in self.sources:
            return True
        if not self.is_walkable(t):
            return False
        if self.predefined is None:
            self.out_units.add(t.unit.filename)
            return True
        return path in self.predefined

    def body_part(self, w, node, lbl):
        """Emits `ada_body_part(node, body)` (D-021). `p_body_part` is a property
        on some BasicDecl subclasses (e.g. BasePackageDecl) and a method on others
        (e.g. ClassicSubpDecl); both shapes are normalized here. A stub
        (`procedure P is separate;`) is paired with its subunit's body. When
        Libadalang finds no body for a subprogram declaration -- its pairing checks
        profile conformance, which needs the formals' types resolved, so with a type
        from a missing dependency it raises or returns nothing -- a syntactic
        pairing (`syntactic_body`) is tried. That finds nothing for an abstract or
        imported subprogram, which has no same-profile body."""
        body = None
        try:
            if isinstance(node, lal.BodyStub):
                body = node.p_next_part_for_decl()
            else:
                bp = getattr(node, "p_body_part", None)
                body = bp() if callable(bp) else bp
        except Exception:
            body = None
        if body is None and isinstance(node, lal.SubpDecl):
            try:
                body = syntactic_body(node)
            except Exception:
                body = None
            if body is not None:
                self.stats["body_part_syntactic"] += 1
        if self.accept(body):
            w.row("ada_body_part", lbl, w.label(node_key(body)))
            self.stats["body_part"] += 1

    def semantics(self, w, node, lbl):
        if isinstance(node, lal.BasicDecl):
            # Separate from the rows below, so a failure here costs only this one.
            # One row per defining name: Libadalang refuses the declaration-level
            # property for a declaration of several names (`A, B : T`).
            try:
                names = node.p_defining_names
                if len(names) == 1:
                    fqs = [node.p_fully_qualified_name]
                else:
                    fqs = [n.p_fully_qualified_name for n in names]
                for fq in fqs:
                    if fq:
                        w.row("ada_qualified_name", lbl, q(fq))
            except Exception:
                pass
            # Also separate: a body pairing that needs name resolution can fail on
            # its own (e.g. a parameter type from a missing dependency).
            self.body_part(w, node, lbl)
        try:
            if isinstance(node, lal.Name) and not node.p_is_defining:
                decl = node.p_referenced_decl()
                if self.accept(decl):
                    w.row("ada_xref", lbl, w.label(node_key(decl)))
                    self.stats["xref"] += 1
            if isinstance(node, lal.Expr):
                t = node.p_expression_type
                if self.accept(t):
                    w.row("ada_expr_type", lbl, w.label(node_key(t)))
                    self.stats["types"] += 1
            if isinstance(node, lal.GenericInstantiation):
                d = node.p_designated_generic_decl
                if self.accept(d):
                    w.row("ada_generic_instantiation", lbl,
                          w.label(node_key(d)))
        except lal.PropertyError:
            self.stats["nameres_errors"] += 1
        except Exception:
            self.stats["nameres_errors"] += 1


def _squash(text: str) -> str:
    """Lower-cased text without whitespace, for comparing source fragments."""
    return re.sub(r"\s+", "", text).lower()


def _profile(spec):
    """The syntactic profile of a SubpSpec: its kind, then (name, mode) for each
    formal, then the formals' type texts and the result type text. An absent mode
    is `in`, as Ada defines it."""
    kind = spec.f_subp_kind.kind_name
    names, types = [], []
    if spec.f_subp_params is not None:
        for ps in spec.f_subp_params.f_params:
            mode = ps.f_mode.kind_name if ps.f_mode is not None else "ModeDefault"
            mode = "ModeIn" if mode == "ModeDefault" else mode
            for dn in ps.f_ids:
                names.append((dn.text.lower(), mode))
                types.append(_squash(ps.f_type_expr.text))
    ret = _squash(spec.f_subp_returns.text) if spec.f_subp_returns is not None else ""
    return (kind, tuple(names)), (tuple(types), ret)


def _decl_list_of_body(region):
    """The declaration list of the body that completes the package whose public or
    private part is `region`, if it can be found."""
    pkg = region.parent
    if isinstance(pkg, lal.GenericPackageInternal):
        pkg = pkg.parent
    body = pkg.p_body_part
    if body is None or body.f_decls is None:
        return None
    return body.f_decls.f_decls


def syntactic_body(decl):
    """Pairs subprogram declaration `decl` with its completion by syntax, for when
    Libadalang's own pairing fails (it needs the formals' types resolved). Ada
    requires a completion to be fully conformant: same name, kind, formal names
    and modes, and lexically equivalent types. Candidates are the same-named bodies
    (and stubs) in the matching region: the package body for a declaration in a
    package spec, else the rest of the same declarative part. A unique candidate
    with the same kind, formal names and modes is the completion; if several
    remain, the type texts decide; still ambiguous gives none."""
    name = decl.p_defining_name.text.lower()
    spec_key, spec_types = _profile(decl.f_subp_spec)
    region = decl.parent.parent
    if isinstance(region, (lal.PublicPart, lal.PrivatePart)):
        lists = [_decl_list_of_body(region)]
    elif isinstance(region, lal.DeclarativePart):
        lists = [decl.parent]
    else:
        return None
    found_decl = False
    candidates = []
    for lst in lists:
        if lst is None:
            continue
        for c in lst:
            if c == decl:
                found_decl = True
                continue
            if lst is decl.parent and not found_decl:
                continue  # a completion follows its declaration
            if not isinstance(c, (lal.BaseSubpBody, lal.SubpBodyStub)):
                continue
            if c.p_defining_name.text.lower() != name:
                continue
            key, types = _profile(c.f_subp_spec)
            if key == spec_key:
                candidates.append((c, types))
    if len(candidates) > 1:
        candidates = [(c, t) for c, t in candidates if t == spec_types]
    return candidates[0][0] if len(candidates) == 1 else None


def find_gpr(src_root: pathlib.Path):
    gpr = os.environ.get("CODEQL_EXTRACTOR_ADA_GPR")
    if not gpr:
        gprs = sorted(src_root.rglob("*.gpr"))
        if len(gprs) == 1:
            gpr = str(gprs[0])
    return gpr


def project_files(src_root: pathlib.Path, gpr):
    if gpr:
        return [f for f in lal.GPRProject(gpr).source_files()
                if pathlib.Path(f).suffix.lower() in EXTENSIONS]
    return sorted(
        str(p) for p in src_root.rglob("*")
        if p.suffix.lower() in EXTENSIONS and p.is_file()
    )


def find_runtime():
    """GNAT runtime source directory for the auto provider, or None."""
    explicit = os.environ.get("CODEQL_EXTRACTOR_ADA_RUNTIME")
    if explicit:
        return explicit if os.path.isdir(explicit) else None
    try:
        out = subprocess.run(["gcc", "-print-file-name=adainclude"],
                             capture_output=True, text=True, timeout=30,
                             check=False).stdout.strip()
    except (OSError, subprocess.SubprocessError):
        return None
    # gcc echoes the bare name back when it has no such directory.
    return out if os.path.isabs(out) and os.path.isdir(out) else None


def runtime_specs(runtime):
    if runtime is None:
        return []
    return sorted(str(p) for p in pathlib.Path(runtime).glob("*.ads"))


def warn_no_runtime(trap_dir: pathlib.Path):
    """One warning diagnostic, both in the database and for the tool-status page."""
    msg = ("No GNAT runtime found: names that mention runtime units (Ada.*, "
           "Interfaces.*, GNAT.*, System.*) will not resolve, which degrades "
           "name resolution of the statements containing them. Install GNAT, or "
           "set CODEQL_EXTRACTOR_ADA_RUNTIME to the runtime's adainclude "
           "directory.")
    print(f"[ada-extractor] warning: {msg}", file=sys.stderr)
    w = TrapWriter()
    f = w.label(file_key(""))
    w.row("files", f, q(""))
    loc = w.label("loc,,0,0,0,0")
    w.row("locations_default", loc, f, "0", "0", "0", "0")
    w.row("empty_location", loc)
    d = w.fresh()
    w.row("diagnostics", d, str(DIAG_WARNING), q("no-runtime"), q(msg), q(msg), loc)
    (trap_dir / "no-runtime.trap").write_text(w.text(), encoding="utf-8")
    diag_dir = os.environ.get(f"CODEQL_EXTRACTOR_{LANG}_DIAGNOSTIC_DIR")
    if diag_dir:
        pathlib.Path(diag_dir).mkdir(parents=True, exist_ok=True)
        (pathlib.Path(diag_dir) / "no-runtime.json").write_text(json.dumps({
            "timestamp": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            "source": {"id": "ada/extractor/no-runtime",
                       "name": "No GNAT runtime found",
                       "extractorName": "ada"},
            "markdownMessage": msg,
            "severity": "warning",
            "visibility": {"statusPage": True, "cliSummaryTable": True,
                           "telemetry": True},
        }), encoding="utf-8")


def build_context(gpr, ada_files, runtime=None) -> lal.AnalysisContext:
    if gpr:
        return lal.GPRProject(gpr).create_context()
    provider = lal.UnitProvider.auto(
        input_files=ada_files + runtime_specs(runtime))
    return lal.AnalysisContext(unit_provider=provider)


# Per-worker state (LAL contexts are neither picklable nor thread-safe, so
# parallelism is one context per forked process).
_state = None


def _init_worker(gpr, files, runtime, predefined, trap_dir, archive_dir):
    global _state
    _state = (build_context(gpr, files, runtime), files,
              Extractor(files, predefined), trap_dir, archive_dir)


def _archive(archive_dir, path, write):
    dest = archive_dir / path.replace(":", "_").lstrip("/")
    dest.parent.mkdir(parents=True, exist_ok=True)
    write(dest)


def _extract_one(f):
    """Pass 1: one project file."""
    ctx, _, ex, trap_dir, archive_dir = _state
    ex.stats = dict.fromkeys(ex.stats, 0)
    ex.out_units = set()
    unit = ctx.get_from_file(f)
    ex.extract_unit(unit, trap_dir)
    path = norm(f)
    _archive(archive_dir, path, lambda d: shutil.copyfile(f, d))
    return path, ex.stats, ex.out_units


def _extract_predefined(filename):
    """Pass 2: one predefined or runtime unit, by Libadalang filename."""
    ctx, files, ex, trap_dir, archive_dir = _state
    ex.stats = dict.fromkeys(ex.stats, 0)
    path = path_of(filename)
    if path == STANDARD_PATH:
        unit = ctx.get_from_file(files[0]).root.p_standard_unit
        _archive(archive_dir, path,
                 lambda d: d.write_text(unit.text, encoding="utf-8"))
    else:
        unit = ctx.get_from_file(filename)
        _archive(archive_dir, path, lambda d: shutil.copyfile(filename, d))
    ex.extract_unit(unit, trap_dir, predefined=True)
    return path, ex.stats


def run_pass(fn, items, jobs, init_args):
    jobs = max(1, min(jobs, len(items) or 1))
    if jobs == 1 or not hasattr(os, "fork"):
        _init_worker(*init_args)
        return list(map(fn, items)), jobs
    import multiprocessing
    with multiprocessing.Pool(jobs, _init_worker, init_args) as pool:
        return pool.map(fn, items, chunksize=4), jobs


def main() -> int:
    t0 = time.monotonic()
    trap_dir = env_path("TRAP_DIR")
    archive_dir = env_path("SOURCE_ARCHIVE_DIR")
    src_root = pathlib.Path.cwd()
    trap_dir.mkdir(parents=True, exist_ok=True)
    archive_dir.mkdir(parents=True, exist_ok=True)

    gpr = find_gpr(src_root)
    print(f"[ada-extractor] project: {gpr or 'none (auto unit provider)'}")
    files = project_files(src_root, gpr)
    runtime = None
    if not gpr:
        runtime = find_runtime()
        print(f"[ada-extractor] runtime: {runtime or 'none'}")
        if runtime is None:
            warn_no_runtime(trap_dir)

    (trap_dir / "metadata.trap").write_text(
        f"sourceLocationPrefix({q(norm(src_root))})\n", encoding="utf-8"
    )

    max_jobs = int(os.environ.get("CODEQL_EXTRACTOR_ADA_JOBS",
                                  str(os.cpu_count() or 1)))
    totals = dict.fromkeys(
        ("nodes", "xref", "types", "diags", "nameres_errors", "comments",
         "body_part", "body_part_syntactic", "predefined_files"), 0)

    results, jobs = run_pass(_extract_one, files, max_jobs,
                             (gpr, files, runtime, None, trap_dir, archive_dir))
    out_units = set()
    for path, st, units in results:
        print(f"[ada-extractor] {path}")
        for k, v in st.items():
            totals[k] += v
        out_units |= units

    # Pass 2: exactly the units pass 1's semantic rows point into.
    by_path = {path_of(u): u for u in out_units}
    t1 = time.monotonic()
    if by_path:
        results, _ = run_pass(
            _extract_predefined, sorted(by_path.values()), max_jobs,
            (gpr, files, runtime, set(by_path), trap_dir, archive_dir))
        for path, st in results:
            print(f"[ada-extractor] predefined: {path}")
            for k, v in st.items():
                totals[k] += v
        totals["predefined_files"] = len(results)
    print(f"[ada-extractor] pass 2: {len(by_path)} predefined units in "
          f"{time.monotonic() - t1:.1f}s")

    dt = time.monotonic() - t0
    print(f"[ada-extractor] {len(files)} files in {dt:.1f}s "
          f"({jobs} jobs): {totals}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
